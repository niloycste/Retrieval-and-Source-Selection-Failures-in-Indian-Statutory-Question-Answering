"""Validate and analyse two completed legal-expert audit packets.

Run only after both annotators have independently completed and frozen the
four CSV files generated by ``prepare_legal_expert_audit.py``.  The script
never fills missing labels.  It writes agreement statistics and a disagreement
file for adjudication.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_DIR = ROOT / "outputs" / "retrieval_legal_expert_audit"

PHASE_FIELDS = {
    "phase1_question_only": {
        "act_identifiability": ["Unique", "Multiple plausible", "Not identifiable", "Unclear"],
        "provision_identifiability": ["Unique", "Multiple plausible", "Not identifiable", "Unclear"],
        "answerable_as_written": ["Yes", "No", "Unclear"],
    },
    "phase2_evidence": {
        "source_a_support": ["Fully", "Partly", "No", "Unclear"],
        "source_b_support": ["Fully", "Partly", "No", "Unclear"],
        "sources_equivalent": ["Yes", "Partly", "No", "Unclear"],
        "reference_answer_correctness": ["Fully", "Partly", "No", "Unclear"],
        "system_answer_correctness": ["Fully", "Partly", "No", "Unclear"],
        "system_answer_completeness": ["Fully", "Partly", "No", "Unclear"],
        "error_materiality": ["None", "Low", "Moderate", "High", "Unclear"],
    },
}


def read_csv(path: Path) -> list[dict]:
    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def cohen_kappa(left: list[str], right: list[str], labels: list[str]) -> float | None:
    n = len(left)
    if not n:
        return None
    observed = sum(a == b for a, b in zip(left, right)) / n
    left_counts, right_counts = Counter(left), Counter(right)
    expected = sum((left_counts[label] / n) * (right_counts[label] / n) for label in labels)
    return None if expected == 1 else (observed - expected) / (1 - expected)


def gwet_ac1(left: list[str], right: list[str], labels: list[str]) -> float | None:
    n, categories = len(left), len(labels)
    if not n or categories < 2:
        return None
    observed = sum(a == b for a, b in zip(left, right)) / n
    left_counts, right_counts = Counter(left), Counter(right)
    pooled = {
        label: (left_counts[label] + right_counts[label]) / (2 * n)
        for label in labels
    }
    expected = sum(value * (1 - value) for value in pooled.values()) / (categories - 1)
    return None if expected == 1 else (observed - expected) / (1 - expected)


def weighted_kappa(left: list[str], right: list[str], labels: list[str]) -> float | None:
    """Quadratic-weighted kappa; labels must be ordered from low to high."""
    pairs = [(a, b) for a, b in zip(left, right) if a in labels and b in labels]
    if not pairs:
        return None
    n, last = len(pairs), max(len(labels) - 1, 1)
    index = {label: position for position, label in enumerate(labels)}
    weights = [[1 - ((i - j) / last) ** 2 for j in range(len(labels))] for i in range(len(labels))]
    observed = sum(weights[index[a]][index[b]] for a, b in pairs) / n
    left_counts = Counter(a for a, _ in pairs)
    right_counts = Counter(b for _, b in pairs)
    expected = sum(
        weights[i][j] * left_counts[labels[i]] * right_counts[labels[j]] / (n * n)
        for i in range(len(labels)) for j in range(len(labels))
    )
    return None if expected == 1 else (observed - expected) / (1 - expected)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--audit-dir", default=str(DEFAULT_DIR))
    args = parser.parse_args()
    audit_dir = Path(args.audit_dir)
    summaries, disagreements = {}, []

    for phase, fields in PHASE_FIELDS.items():
        left_rows = read_csv(audit_dir / f"annotator_A_{phase}.csv")
        right_rows = read_csv(audit_dir / f"annotator_B_{phase}.csv")
        if [row["case_id"] for row in left_rows] != [row["case_id"] for row in right_rows]:
            raise ValueError(f"case order differs between annotators in {phase}")
        if len(left_rows) != 80:
            raise ValueError(f"expected 80 cases in {phase}, found {len(left_rows)}")
        summaries[phase] = {}
        for field, labels in fields.items():
            left = [row[field].strip() for row in left_rows]
            right = [row[field].strip() for row in right_rows]
            for annotator, values in (("A", left), ("B", right)):
                invalid = [value for value in values if value not in labels]
                if invalid:
                    counts = Counter(invalid)
                    raise ValueError(f"{phase}/{field}/annotator {annotator} has missing or invalid labels: {counts}")
            raw = sum(a == b for a, b in zip(left, right)) / len(left)
            result = {
                "n": len(left),
                "raw_agreement": round(raw, 6),
                "cohen_kappa": None if (value := cohen_kappa(left, right, labels)) is None else round(value, 6),
                "gwet_ac1": None if (value := gwet_ac1(left, right, labels)) is None else round(value, 6),
                "annotator_a_distribution": dict(Counter(left)),
                "annotator_b_distribution": dict(Counter(right)),
            }
            if field == "error_materiality":
                value = weighted_kappa(left, right, ["None", "Low", "Moderate", "High"])
                result["quadratic_weighted_kappa_excluding_unclear"] = None if value is None else round(value, 6)
            summaries[phase][field] = result
            for left_row, right_row, a, b in zip(left_rows, right_rows, left, right):
                if a != b:
                    disagreements.append({
                        "case_id": left_row["case_id"], "phase": phase,
                        "field": field, "annotator_a_label": a,
                        "annotator_b_label": b, "adjudicated_label": "",
                        "adjudicator_id": "", "adjudication_rationale": "",
                    })

    output = audit_dir / "agreement_summary.json"
    output.write_text(json.dumps({
        "status": "complete independent labels validated",
        "agreement": summaries,
        "n_disagreements": len(disagreements),
        "notes": [
            "Gwet AC1 is reported because marginal prevalence may be imbalanced.",
            "Quadratic weighted kappa excludes Unclear labels and is used only for ordered materiality.",
            "Adjudicated labels must not overwrite the two original annotation files.",
        ],
    }, indent=2), encoding="utf-8")
    fields = [
        "case_id", "phase", "field", "annotator_a_label",
        "annotator_b_label", "adjudicated_label", "adjudicator_id",
        "adjudication_rationale",
    ]
    with (audit_dir / "adjudication_template.csv").open(
        "w", encoding="utf-8-sig", newline=""
    ) as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(disagreements)
    print(json.dumps({
        "status": "PASS", "agreement_summary": str(output),
        "n_disagreements": len(disagreements),
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
